"""Run the whole analysis without the web app and write the results to outputs/.

    python export_report.py                         # uses the first log found in data/real
    python export_report.py --log data/real/BPI_Challenge_2012.xes.gz
    python export_report.py --llm                   # also let Gemini explain the facts (needs GEMINI_API_KEY)

Writes: report.md, facts.json, as_is.mmd, to_be.mmd and CSV tables (step metrics, automation scores,
rework, outcomes, improvements). Use these files in your README and in the BRD/FSD.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from unjam.config import DATA_DIR, OUTPUT_DIR, ROOT, list_local_logs
from unjam.decisions import Assumptions, AutomationConfig
from unjam.loader import LogFormatError, load_log
from unjam.pipeline import analyse, run_checks
from unjam.report import export_all
from unjam.utils import dataset_title, fmt_hours, fmt_int


def main() -> int:
    ap = argparse.ArgumentParser(description="UnJam: headless analysis and report export")
    ap.add_argument("--log", help="path to .xes / .xes.gz / .csv / .zip (default: first file in data/real)")
    ap.add_argument("--out", default=str(OUTPUT_DIR), help="output folder (default: outputs)")
    ap.add_argument("--llm", action="store_true", help="use Gemini to explain the computed facts")
    ap.add_argument("--no-docs", action="store_true", help="do not write docs/PROCESS_MAPS.md and docs/RESULTS.md")
    ap.add_argument("--reduction", type=float, default=0.5, help="to-be assumption: automated steps wait this much less (0-1)")
    args = ap.parse_args()

    path = Path(args.log) if args.log else (list_local_logs() or [None])[0]
    if path is None or not path.exists():
        print("No event log found.\n"
              f"1. Download BPI_Challenge_2012.xes.gz (see data/real/README.md)\n2. Put it in {DATA_DIR}\n3. Run this command again.")
        return 1

    try:
        events, quality = load_log(path)
    except LogFormatError as exc:
        print(f"Could not read {path.name}: {exc}")
        return 1
    a = analyse(events, quality, dataset_title(path.name))
    res = export_all(a, AutomationConfig(), Assumptions(args.reduction), Path(args.out), use_llm=args.llm)

    if not args.no_docs:
        out = Path(args.out)
        as_is = (out / "as_is.mmd").read_text(encoding="utf-8")
        to_be = (out / "to_be.mmd").read_text(encoding="utf-8")
        docs = ROOT / "docs"
        (docs / "PROCESS_MAPS.md").write_text(
            f"# Discovered process maps\n\nGenerated by `python export_report.py` from `{path.name}`. "
            "Do not edit by hand; run the command again after changing the data or the settings.\n\n"
            f"## As-is (discovered from the log)\n\n```mermaid\n{as_is}\n```\n\n"
            f"## To-be (top automation steps highlighted)\n\n```mermaid\n{to_be}\n```\n",
            encoding="utf-8")
        (docs / "RESULTS.md").write_text((out / "report.md").read_text(encoding="utf-8"), encoding="utf-8")
        print("Also wrote docs/PROCESS_MAPS.md and docs/RESULTS.md")

    print(f"\nUnJam analysed {fmt_int(len(a.cases))} cases / {fmt_int(len(a.inst))} steps from {path.name}")
    print(f"Median case duration: {fmt_hours(a.durations['median_h'])}  |  slowest 10% start at {fmt_hours(a.durations['p90_h'])}")
    print("Checks:")
    for c in run_checks(a):
        print(f"  [{'ok' if c['passed'] else 'FAIL'}] {c['check']}: {c['result']}")
    print(f"Findings written by: {res['narrative_source']}")
    print(f"Files in {args.out}: {', '.join(res['files'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
